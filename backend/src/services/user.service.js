const prisma = require("../lib/prisma");
const { UUID_REGEX } = require("../middlewares/clientIdentity");

/**
 * Initializes a new user or retrieves an existing user by ID.
 * Generates a standard UUID via Prisma default(uuid()) when creating a new record.
 * 
 * @param {Object} params
 * @param {string} [params.userId] - Optional existing user UUID to look up and reuse
 * @param {string} [params.name] - User or buyer name
 * @param {string} [params.email] - Optional contact email
 * @param {string} [params.phone] - Optional contact phone
 * @returns {Promise<Object>} User record with business relation
 */
const initOrGetUser = async ({ userId, name, email, phone } = {}) => {
  // 1. If existing userId is provided and valid, attempt to retrieve
  if (userId && typeof userId === "string" && UUID_REGEX.test(userId.trim())) {
    const existing = await prisma.user.findUnique({
      where: { id: userId.trim() },
      include: { business: true },
    });
    if (existing) {
      return {
        user: existing,
        isNew: false,
      };
    }
  }

  // 2. If email provided, check if existing user matches email
  if (email && typeof email === "string" && email.trim()) {
    const cleanEmail = email.trim().toLowerCase();
    const existingByEmail = await prisma.user.findUnique({
      where: { email: cleanEmail },
      include: { business: true },
    });
    if (existingByEmail) {
      return {
        user: existingByEmail,
        isNew: false,
      };
    }
  }

  // 3. Create a new user with UUID generated by Prisma
  const trimmedName = typeof name === "string" && name.trim() ? name.trim() : "Guest Buyer";
  const trimmedEmail = typeof email === "string" && email.trim() ? email.trim().toLowerCase() : null;
  const trimmedPhone = typeof phone === "string" && phone.trim() ? phone.trim() : null;

  const newUser = await prisma.user.create({
    data: {
      name: trimmedName,
      email: trimmedEmail,
      phone: trimmedPhone,
      role: "BUYER",
    },
    include: { business: true },
  });

  return {
    user: newUser,
    isNew: true,
  };
};

/**
 * Fetch a user by their UUID
 * @param {string} id - User UUID
 * @returns {Promise<Object|null>}
 */
const getUserById = async (id) => {
  if (!id || typeof id !== "string" || !UUID_REGEX.test(id.trim())) {
    return null;
  }

  return await prisma.user.findUnique({
    where: { id: id.trim() },
    include: { business: true },
  });
};

module.exports = {
  initOrGetUser,
  getUserById,
};

